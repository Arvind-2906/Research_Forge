"""ResearchForge AI Engine - Report Generation Agent.

Produces a comprehensive, publication-ready research report in structured Markdown,
linking citations and persisting ResearchReport and ReportCitation in Neon PostgreSQL.
"""

from datetime import datetime, timezone
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field

from database.repositories import report_repository, event_repository
from utils.logger import logger


class GeneratedReportResult(BaseModel):
    report_id: str
    title: str
    executive_summary: str
    markdown_content: str
    word_count: int
    citation_count: int


class ReportGenerationAgent:
    """Agent that compiles all research artifacts into a cohesive final Markdown report."""

    async def run(
        self,
        run_id: str,
        research_query: str,
        specification: Dict[str, Any],
        synthesis: Dict[str, Any],
        citations: List[Dict[str, Any]],
        contradictions: Optional[List[Dict[str, Any]]] = None,
    ) -> GeneratedReportResult:
        """Assembles Markdown report and saves it to Neon PostgreSQL."""
        logger.info(f"[ReportGenerationAgent] Generating comprehensive report for run {run_id}")

        topic = specification.get("topic") or research_query
        title = f"Empirical Research Report: {topic.title()}"
        summary = synthesis.get("executive_summary", "")

        # Build Markdown content
        now_str = datetime.now(timezone.utc).strftime("%B %d, %Y")
        md_lines = [
            f"# {title}",
            f"\n*Generated by ResearchForge Autonomous Agent Workspace on {now_str}*",
            "\n---",
            "\n## Executive Summary",
            f"\n{summary}",
            "\n## Research Objective & Scope",
            f"\n**Core Objective**: {research_query}",
            f"\n- **Domain**: {specification.get('domain', 'General')}",
            f"- **Research Scope**: {specification.get('scope', 'Broad')}",
            f"- **Depth**: {specification.get('depth', 'in-depth')}",
            "\n---",
            "\n## Key Findings & Synthesis",
        ]

        # Add synthesis sections
        sections = synthesis.get("sections", [])
        for s in sections:
            sec_title = s.get("title", "Section")
            sec_content = s.get("content", "")
            md_lines.append(f"\n### {sec_title}\n")
            md_lines.append(sec_content)

            key_findings = s.get("key_findings", [])
            if key_findings:
                md_lines.append("\n**Key Takeaways:**")
                for kf in key_findings:
                    md_lines.append(f"- {kf}")

        # Add contradictions / nuance section if any
        if contradictions:
            md_lines.append("\n---\n## Comparative Analysis & Discrepancies")
            md_lines.append("\nOur verification identified the following differing perspectives or conflicting data points:")
            for c in contradictions:
                topic_str = c.get("topic", "Data discrepancy")
                explanation = c.get("nature_of_conflict", "")
                md_lines.append(f"\n- **{topic_str}**: {explanation}")

        # Add References section
        md_lines.append("\n---\n## References & Sources")
        if citations:
            for c in citations:
                num = c.get("citation_number", 1)
                text = c.get("citation_text") or c.get("source_url") or "Source reference"
                url = c.get("source_url")
                if url:
                    md_lines.append(f"{num}. [{text}]({url})")
                else:
                    md_lines.append(f"{num}. {text}")
        else:
            md_lines.append("*No external citations recorded.*")

        full_markdown = "\n".join(md_lines)
        word_count = len(full_markdown.split())

        # Persist report in Neon PostgreSQL via report_repository
        saved_report = await report_repository.create_or_update_report(
            run_id=run_id,
            title=title,
            executive_summary=summary,
            content_markdown=full_markdown,
            status="COMPLETED",
            metadata={"word_count": word_count, "citation_count": len(citations)},
        )

        # Persist citations in Neon PostgreSQL
        await report_repository.create_citations(
            report_id=saved_report["id"],
            citations=citations,
        )

        await event_repository.create_event(
            run_id=run_id,
            event_type="REPORT_GENERATED",
            message=f"Research report '{title}' generated successfully ({word_count} words, {len(citations)} citations)",
            agent_name="ReportGenerationAgent",
            payload={"report_id": saved_report["id"], "word_count": word_count, "citation_count": len(citations)},
        )

        return GeneratedReportResult(
            report_id=saved_report["id"],
            title=title,
            executive_summary=summary,
            markdown_content=full_markdown,
            word_count=word_count,
            citation_count=len(citations),
        )


report_generation_agent = ReportGenerationAgent()

